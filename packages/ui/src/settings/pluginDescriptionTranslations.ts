/**
 * 取插件的中文简介：仅 zh 语言、仅 Codex 聚合目录（其他市场/语言走原文）。
 * 目录以后新增插件时这里查不到，回落到英文原文即可，不影响功能。
 */
export function resolvePluginDescriptionZh(
  pluginId: string,
  locale: string,
): string | undefined {
  if (!locale.toLowerCase().startsWith("zh")) {
    return undefined;
  }
  const at = pluginId.lastIndexOf("@");
  if (at <= 0 || pluginId.slice(at + 1) !== CODEX_CATALOG_MARKETPLACE_ID) {
    return undefined;
  }
  return CODEX_PLUGIN_DESCRIPTION_ZH[pluginId.slice(0, at)];
}
